  const b = await chromium.launch(require('./_launch'));
  const log = (...a) => console.log(...a);
  const errs = [];
  // 主人（手機版）
  let ctx = await b.newContext({ viewport: { width: 390, height: 844 } });
  let p = await ctx.newPage(); p.on('pageerror', (e) => errs.push(e.message)); p.on('dialog', (d) => d.accept());
  await p.goto(U + '#/'); await p.waitForTimeout(900);
  log('new visitor lands on home', await p.isVisible('.quick-rec'));
  log('owner tour shown', await p.isVisible('.tour-dlg'), await p.textContent('.tour-dlg h2'));
  await p.screenshot({ path: 'r13-tour1.png' });
