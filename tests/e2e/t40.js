  await p.goto(U + '#/new/happy'); await p.waitForTimeout(700);
  await p.evaluate(() => document.querySelectorAll('.tour-dlg').forEach((e) => e.remove()));
  await p.evaluate(() => { localStorage.removeItem('tourDone'); });
  await p.fill('#f-title', '舊的'); await p.click('#save'); await p.waitForTimeout(900);
  await p.goto(U + '#/'); await p.reload(); await p.waitForTimeout(800);
  log('existing user no tour', !(await p.isVisible('.tour-dlg')));
