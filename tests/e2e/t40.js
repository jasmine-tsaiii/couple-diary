  await p.click('#tour-next'); await p.waitForTimeout(200);
  log('page3', await p.textContent('.tour-dlg h2'));
  await p.click('#tour-next'); await p.waitForTimeout(200);
  log('page4 signup', await p.textContent('.tour-dlg h2'), await p.isVisible('#tour-signup'), await p.textContent('#tour-next'), 'no skip on last', !(await p.isVisible('#tour-skip')));
